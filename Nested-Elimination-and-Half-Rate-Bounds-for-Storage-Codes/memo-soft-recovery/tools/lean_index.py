#!/usr/bin/env python3
"""Generate the memo's Lean index and axiom audit from its manuscript and library.

Usage from any directory: python3 tools/lean_index.py [--check]

The index lists local formal-status and inline Lean references, and qualified
imported declarations. PaperAxioms.lean additionally checks all public memo
theorems and the three imported XOR witness declarations. --check reports
stale outputs without rewriting them. Lean, not this script, checks proofs.
"""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = ROOT / "paper" / "sections"
LIBRARY = ROOT / "lean" / "SoftRecovery"
FORMAL = re.compile(r"\\(?:formal|partformal)\{([^{}]+)\}\{([^{}]+)\}")
INLINE = re.compile(r"\\lean\{([^{}]+)\}")
IMPORTED = re.compile(r"\\leanfile\{((?:HalfRate|MotionDepthCodes)\.[^{}]+)\}")
DECLARATION = re.compile(
    r"^(?:@\[[^\n]*\]\s*)?(?:noncomputable\s+)?"
    r"(theorem|def|abbrev|structure)\s+([A-Za-z_][A-Za-z_0-9.']*)", re.M
)
WITNESSES = [
    "TransposeFollowup.SeparatorSharpness.xorCode_correct",
    "TransposeFollowup.SeparatorSharpness.xorCode_helper_bits",
    "TransposeFollowup.SeparatorSharpness.fullFamily_deficit",
]


def generate():
    declaration_files, public_theorems = {}, set()
    for source in sorted(LIBRARY.glob("*.lean")):
        for kind, name in DECLARATION.findall(source.read_text()):
            if name in declaration_files:
                raise ValueError(f"Duplicate declaration: {name}")
            declaration_files[name] = source.name
            if kind == "theorem":
                public_theorems.add(name)

    by_file, imported = {}, set()
    for source in sorted(SECTIONS.glob("*.tex")):
        if source.name == "leanindex.tex":
            continue
        text = source.read_text()
        imported.update(IMPORTED.findall(text))
        for filename, names in FORMAL.findall(text):
            for name in (n.strip() for n in names.split(",") if n.strip()):
                if declaration_files.get(name) != filename:
                    raise ValueError(f"{source.name}: {name} is not declared in {filename}")
                by_file.setdefault(filename, set()).add(name)
        for name in INLINE.findall(text):
            if name not in declaration_files:
                raise ValueError(f"{source.name}: unknown local declaration {name}")
            by_file.setdefault(declaration_files[name], set()).add(name)

    cited = set().union(*by_file.values()) if by_file else set()
    index = [
        r"\section{Index of Lean declarations}\label{sec:leanindex}",
        "",
        r"Local names are relative to \texttt{SoftRecovery}; imported names are fully",
        r"qualified. The index is generated",
        r"from the manuscript together with the axiom audit (\cref{sec:verification}).",
        "",
    ]
    for filename, names in sorted(by_file.items()):
        index += [
            r"\paragraph{\texttt{" + filename.replace("_", r"\_") + "}}",
            r"{\small\raggedright\leanlist{" + ",".join(sorted(names)) + r"}.\par}",
            "",
        ]
    if imported:
        index += [
            r"\paragraph{Imported declarations}",
            r"{\small\raggedright\leanlist{" + ",".join(sorted(imported)) + r"}.\par}",
            "",
        ]
    audit_names = sorted({"SoftRecovery." + n for n in public_theorems | cited}
                         | imported | set(WITNESSES))
    audit = [
        "import SoftRecovery",
        "",
        "/-! Generated by tools/lean_index.py from the manuscript and public library.",
        "Audit every cited declaration, all public memo theorems, and the reused XOR",
        "witness. Permitted axioms: propext, Classical.choice, Quot.sound. -/",
        "",
        *["#print axioms " + name for name in audit_names],
        "",
    ]
    return {
        SECTIONS / "leanindex.tex": "\n".join(index),
        ROOT / "lean" / "PaperAxioms.lean": "\n".join(audit),
    }, len(cited) + len(imported), len(audit_names)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs, cited, audited = generate()
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        parser.exit(1, "Stale generated files: " + ", ".join(stale) + "\n")
    print(f"{cited} manuscript declarations; {audited} declarations in the axiom audit.")


if __name__ == "__main__":
    main()
