"""Generate the binary seed recovery certificate, checked independently by Lean.

Run from any directory: python3 tools/seed_recovery_certificate.py
The seed is read from the sibling Paper 17. No search or solver is used.
"""
import json
from pathlib import Path

paper = Path(__file__).resolve().parents[1]
seed_path = paper.parent / (
    'Order-Symmetry-and-the-Swap-A-Synthesis-of-Matrix-Transposition-on-Tapes/'
    'tools/data/aperiodic_d6_dim25.json')
seed = json.loads(seed_path.read_text())
d = seed['n']
assert d == 6
cls = {c: j for j, group in enumerate(seed['classes']) for c in group}
generators = seed['kernel_basis']
pivots = [(g & -g).bit_length() - 1 for g in generators]
assert len(generators) == len(set(pivots)) == 25
assert all(((g >> p) & 1) == int(i == j)
           for i, g in enumerate(generators) for j, p in enumerate(pivots))
equations = []
for c in range(d):
    for r in range(d):
        row = 1 << (c * d + r)
        for k, bit in enumerate(seed['a'][cls[c]][r]):
            if bit:
                i, e = divmod(k, d)
                row ^= 1 << (i * d + (e + c) % d)
        equations.append(row)
elimination = {}
for i, row in enumerate(equations):
    witness = 1 << i
    while row:
        p = row.bit_length() - 1
        if p not in elimination:
            elimination[p] = (row, witness)
            break
        old, old_witness = elimination[p]
        row ^= old
        witness ^= old_witness
assert len(elimination) == 11
supports = []
for i in range(d * d):
    row = 1 << i
    for g, p in zip(generators, pivots):
        if (g >> i) & 1:
            row ^= 1 << p
    witness = 0
    while row:
        p = row.bit_length() - 1
        old, old_witness = elimination[p]
        row ^= old
        witness ^= old_witness
    supports.append([divmod(j, d) for j in range(d * d) if (witness >> j) & 1])
rows = ['  [' + ', '.join(f'({i}, {j})' for i, j in row) + ']' for row in supports]
output = ('import SwapRigidity.AperiodicExample\n\n'
          '/-! Recovery data generated by tools/seed_recovery_certificate.py.\n'
          'ConstructionSeedExact checks the resulting linear identity in the kernel. -/\n\n'
          'namespace SharedDecoders\n\n'
          'def binarySeedRecoverySupports : List (List (ZMod 6 × ZMod 6)) :=\n'
          '[' + ',\n'.join(rows) + ']\n\nend SharedDecoders\n')
target = paper / 'lean/SharedDecoders/ConstructionSeedExactData.lean'
target.write_text(output)
print(f'Generated {len(supports)} recovery rows; defect rank {len(elimination)}.')
