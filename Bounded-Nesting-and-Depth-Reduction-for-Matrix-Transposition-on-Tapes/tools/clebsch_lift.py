#!/usr/bin/env python3
"""Exact GF(2) nullity of the lifted Clebsch code on an explicit 16-sheeted permutation lift.

Usage (from the paper directory, i.e. the parent of paper/ and tools/):

    python3 tools/clebsch_lift.py [--sheets D] [--seed S]

The Clebsch graph has vertex set F_2^4; two vertices are adjacent when they differ in exactly one
coordinate or in all four. Its fundamental group with respect to the breadth-first spanning tree
from 0000 (neighbours scanned in increasing order) is free on the 25 non-tree edges. Each non-tree
edge {u, v} with u < v, taken in lexicographic order, receives a permutation pi of {0, ..., D-1},
generated by the Fisher-Yates shuffle driven by the linear congruential generator
x -> (1103515245 x + 12345) mod 2^31 started at the seed (default 1), where the shuffle at
position i uses x mod (i + 1). The lift has the vertices (i, u), i < D, and the edges
(i, u) ~ (pi(i), v) for the non-tree edges (oriented from u to v, u < v) and (i, u) ~ (i, v) for
the tree edges. The script prints the GF(2) rank and nullity of I + A, where A is the adjacency
matrix of the lift. The lift of M = I + A_Clebsch along this cover is exactly this matrix.

With the default parameters the output is "GF(2) rank of I + A: 246; nullity: 10". The paper uses
only this single explicit lift; other seeds give other lifts (seeds 2 to 8 give nullity 10 or 12).
With --sheets 1 the script returns the Clebsch code itself (rank 6, nullity 10). No external
packages are needed. The computation is exact (integers as bit vectors).
"""
import argparse


def clebsch():
    verts = list(range(16))
    gens = [1, 2, 4, 8, 15]
    adj = {v: sorted(v ^ g for g in gens) for v in verts}
    return verts, adj


def bfs_tree(verts, adj, root=0):
    parent = {root: None}
    order = [root]
    i = 0
    while i < len(order):
        v = order[i]
        i += 1
        for w in adj[v]:
            if w not in parent:
                parent[w] = v
                order.append(w)
    tree = {frozenset((v, p)) for v, p in parent.items() if p is not None}
    return tree


class LCG:
    def __init__(self, seed):
        self.x = seed % (1 << 31)

    def next(self):
        self.x = (1103515245 * self.x + 12345) % (1 << 31)
        return self.x


def permutation(rng, d):
    p = list(range(d))
    for i in range(d - 1, 0, -1):
        j = rng.next() % (i + 1)
        p[i], p[j] = p[j], p[i]
    return p


def gf2_rank(rows):
    """Rank over GF(2) of a list of rows given as Python integers (bit vectors)."""
    rank = 0
    pivots = {}
    for r in rows:
        while r:
            h = r.bit_length() - 1
            if h in pivots:
                r ^= pivots[h]
            else:
                pivots[h] = r
                rank += 1
                break
    return rank


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheets", type=int, default=16)
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()
    d = args.sheets
    verts, adj = clebsch()
    tree = bfs_tree(verts, adj)
    edges = sorted({(min(u, v), max(u, v)) for u in verts for v in adj[u]})
    assert len(edges) == 40 and len(tree) == 15
    rng = LCG(args.seed)
    perm = {}
    for (u, v) in edges:
        if frozenset((u, v)) in tree:
            perm[(u, v)] = list(range(d))
        else:
            perm[(u, v)] = permutation(rng, d)
    nontree = sum(1 for e in edges if frozenset(e) not in tree)
    n = 16 * d

    def idx(i, u):
        return i * 16 + u

    rows = [1 << idx(i, u) for i in range(d) for u in range(16)]  # the identity
    for (u, v) in edges:
        p = perm[(u, v)]
        for i in range(d):
            a, b = idx(i, u), idx(p[i], v)
            rows[a] ^= 1 << b
            rows[b] ^= 1 << a
    r = gf2_rank(rows)
    print(f"Clebsch graph: 16 vertices, 40 edges, {nontree} non-tree edges")
    print(f"lift: {d} sheets, {n} vertices, seed {args.seed}")
    print(f"GF(2) rank of I + A: {r}; nullity: {n - r}")


if __name__ == "__main__":
    main()
