#!/usr/bin/env python3
"""Generate the statement index and axiom commands; this does not verify proofs.

Run from any directory: python3 tools/statement_index.py [--check]
Paths in generated material are relative to this paper's directory.
"""

import argparse
import hashlib
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
INDEX = PAPER / "sections" / "theorem-index.tex"
MD_INDEX = ROOT / "FORMALIZATION-INDEX.md"
AXIOMS = ROOT / "lean" / "PaperAxioms.lean"
FORMAL = re.compile(r"\\formal\{([^{}]+)\}\{([^{}]+)\}")
RESULT = re.compile(
    r"\\begin\{(theorem|lemma|corollary|proposition|definition)\}"
    r"(?:\[([^\]]*)\])?(.*?)\\end\{\1\}", re.DOTALL
)


def read_statements():
    main = (PAPER / "main.tex").read_text()
    sections = re.findall(r"\\input\{(sections/[^}]+)\}", main)
    entries, labels = [], set()
    for section in sections:
        path = PAPER / (section + ".tex")
        if path == INDEX:
            continue
        source = path.read_text()
        for match in RESULT.finditer(source):
            kind, title, body = match.groups()
            label_match = re.search(r"\\label\{([^}]+)\}", body)
            if label_match is None or not title:
                raise ValueError(f"Missing label or title in {path.name}")
            label = label_match.group(1)
            if label in labels:
                raise ValueError(f"Duplicate label: {label}")
            labels.add(label)
            formal = FORMAL.search(body)
            lean_file, declarations = None, []
            status = "Definition"
            if formal:
                lean_file = formal.group(1).strip()
                declarations = [d.strip() for d in formal.group(2).split(",") if d.strip()]
                if (Path(lean_file).is_absolute() or ".." in Path(lean_file).parts
                        or not (ROOT / "lean" / lean_file).is_file()):
                    raise ValueError(f"Invalid Lean source path: {lean_file}")
                if not declarations or any(not re.fullmatch(r"SourceCovers\.[A-Za-z0-9_'.]+", d)
                                           for d in declarations):
                    raise ValueError(f"Invalid qualified Lean declaration: {label}")
                if "\\notformalized" in body:
                    raise ValueError(f"Conflicting proof statuses: {label}")
                status, proof_env = "Lean-verified", "outline"
            elif kind != "definition":
                if "\\notformalized" not in body:
                    raise ValueError(f"Missing proof status: {label}")
                status, proof_env = "Written proof", "informalproof"
            if kind != "definition":
                following = source[match.end():]
                if not re.match(r"\s*\\begin\{" + proof_env + r"\}", following):
                    raise ValueError(f"Missing {proof_env} after {label}")
                if "\\end{" + proof_env + "}" not in following:
                    raise ValueError(f"Unclosed {proof_env}: {label}")
            entries.append({
                "kind": kind,
                "title": " ".join(title.split()),
                "label": label,
                "path": path.relative_to(ROOT).as_posix(),
                "line": source.count("\n", 0, match.start()) + 1,
                "digest": hashlib.sha256(match.group(0).encode()).hexdigest(),
                "status": status,
                "lean_file": lean_file,
                "declarations": declarations,
            })
    return entries


def render(entries):
    definitions = sum(e["kind"] == "definition" for e in entries)
    results = len(entries) - definitions
    verified = sum(e["status"] == "Lean-verified" and e["kind"] != "definition" for e in entries)
    formal_entries = [e for e in entries if e["declarations"]]
    declarations = sorted({d for e in formal_entries for d in e["declarations"]})
    tex = [
        "% Generated by tools/statement_index.py; do not edit by hand.",
        r"\section{Statement index}\label{sec:theorem-index}",
        f"The manuscript contains {results} numbered results and {definitions} numbered",
        f"definitions. Lean-verified results: {verified}; results with complete written",
        f"proofs only: {results - verified}. A star marks a Lean-verified statement.",
        "Stable labels below identify the statements; they are not Lean declaration names.",
        r"Source files and statement fingerprints are listed in \path{FORMALIZATION-INDEX.md}.",
        r"\begingroup\small",
        r"\begin{longtable}{@{}p{.15\textwidth}p{.38\textwidth}p{.41\textwidth}@{}}",
        r"\toprule Reference & Statement & Stable label \\",
        r"\midrule\endfirsthead",
        r"\toprule Reference & Statement & Stable label \\",
        r"\midrule\endhead",
        r"\bottomrule\endfoot",
    ]
    md = [
        "# Formalization statement index", "",
        "Generated by `tools/statement_index.py`; do not edit by hand.", "",
        f"**{results} numbered results; {definitions} numbered definitions.**",
        f"**{verified} Lean-verified {'result' if verified == 1 else 'results'}; "
        f"{results - verified} results with written proofs only.**",
        "The status column records the manuscript's proof status. Stable labels are",
        "manuscript identifiers, not Lean declaration names. The exact statements and",
        "inherited hypotheses are in the linked LaTeX sections and compiled paper.",
        "Fingerprints cover each statement environment, including its label and status;",
        "they detect textual changes and do not certify mathematical correctness.", "",
        "See [FORMALIZATION.md](FORMALIZATION.md) for the dependency and reuse plan.", "",
        "| Stable label | Kind | Statement | Status | Source |", "|---|---|---|---|---|",
    ]
    for i, e in enumerate(entries):
        star = r"${}^{*}$" if e["status"] == "Lean-verified" else ""
        # Use longtable's row spacing so continuation headers stay attached.
        # Keep the last two rows together instead of orphaning the final row.
        ending = r" \\"
        if i + 1 < len(entries):
            ending += ("*" if i + 2 == len(entries) else "") + "[2pt]"
        tex.append(
            rf"\cref{{{e['label']}}}{star} & {e['title']} & "
            rf"\leanname{{{e['label']}}}" + ending
        )
        md.append(
            f"| `{e['label']}` | {e['kind'].capitalize()} | {e['title']} | {e['status']} | "
            f"[{Path(e['path']).name}:{e['line']}]({e['path']}#L{e['line']}) |"
        )
    tex.extend([r"\end{longtable}", r"\endgroup", ""])
    tex.extend([
        r"\noindent\begin{minipage}{\textwidth}",
        r"\paragraph{Verified declarations.}",
        r"The following declarations are audited by the generated \path{lean/PaperAxioms.lean}.",
        r"They depend at most on \leanname{propext}, \leanname{Classical.choice} and",
        r"\leanname{Quot.sound}. Earlier-paper declarations cited for reuse are verified there.\par",
    ])
    md.extend(["", "## Verified declarations", "",
               "The generated [axiom audit](lean/PaperAxioms.lean) checks these declarations.", ""])
    # Keep each file heading with its declarations, but let the growing
    # declaration catalogue break across pages between entries.
    for i, e in enumerate(formal_entries):
        if i:
            tex.append(r"\noindent\begin{minipage}{\textwidth}")
        tex.extend([rf"\noindent\leanfile{{{e['lean_file']}}}:\par",
                    r"{\small\raggedright\leanlist{" + ",".join(e["declarations"]) + r"}\par}",
                    r"\end{minipage}\par\smallskip"])
        md.extend([f"- `{e['label']}`: [{e['lean_file']}](lean/{e['lean_file']})",
                   "  — " + ", ".join(f"`{d}`" for d in e["declarations"]) + "."])
    tex.append("")
    md.extend(["", "## Statement SHA-256 fingerprints", "", "```text"])
    md.extend(f"{e['digest']}  {e['label']}" for e in entries)
    md.extend(["```", ""])
    axioms = ["import SourceCovers", "",
              "/-! Generated by tools/statement_index.py from the manuscript's formal citations.",
              "Allowed axioms: propext, Classical.choice, Quot.sound. -/", ""]
    axioms.extend(f"#print axioms {d}" for d in declarations)
    axioms.append("")
    return {INDEX: "\n".join(tex), MD_INDEX: "\n".join(md), AXIOMS: "\n".join(axioms)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the generated files are stale")
    args = parser.parse_args()
    entries = read_statements()
    for path, content in render(entries).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale generated file: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
    results = sum(e["kind"] != "definition" for e in entries)
    verified = sum(e["status"] == "Lean-verified" and e["kind"] != "definition" for e in entries)
    print(f"{'Checked' if args.check else 'Generated'} index: "
          f"{results} results ({verified} formal), {len(entries) - results} definitions; "
          "axiom commands generated, not executed.")


if __name__ == "__main__":
    main()
