#!/usr/bin/env python3
"""Generate the Lean index appendix and PaperAxioms.lean from the LaTeX sources.

Usage (from the paper directory, i.e. the parent of paper/ and lean/):

    python3 tools/lean_index.py               # writes both files
    python3 tools/lean_index.py --index-only  # writes only paper/sections/leanindex.tex

Collects every declaration named in a \\formal{file}{names} or \\partformal{file}{names}{...}
line of paper/sections/*.tex, and every name in a \\lean{name} reference to this library (names of
earlier libraries of the series, starting with "Transpose.", "MotionDepthCodes.", "CircularMemo.",
"DirectedRecovery.", "HalfRate.", "BoundedNesting." or "SimpleGraph.", are tracked separately and
verified via `#print axioms` in PaperAxioms.lean), and writes
  * paper/sections/leanindex.tex: the declarations of DirectedReciprocity grouped by Lean module;
  * lean/PaperAxioms.lean: imports and one `#print axioms` per declaration (not with
    --index-only), including cited declarations of earlier libraries.
Declarations are relative to the namespace DirectedReciprocity; files are relative to
lean/DirectedReciprocity/.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = ROOT / "paper" / "sections"
FORMAL = re.compile(r"\\(?:formal|partformal)\{([^{}]+)\}\{([^{}]+)\}")
INLINE = re.compile(r"\\lean\{([^{}]+)\}")
FOREIGN = (
    "Transpose.",
    "MotionDepthCodes.",
    "CircularMemo.",
    "DirectedRecovery.",
    "HalfRate.",
    "BoundedNesting.",
    "SimpleGraph.",
)


def collect():
    by_file, inline, foreign = {}, set(), set()
    for tex in sorted(SECTIONS.glob("*.tex")):
        if tex.name == "leanindex.tex":
            continue
        text = tex.read_text()
        for file, names in FORMAL.findall(text):
            decls = [n.strip() for n in names.split(",") if n.strip()]
            by_file.setdefault(file.strip(), set()).update(decls)
        for raw in INLINE.findall(text):
            name = raw.strip()
            if name.startswith(FOREIGN):
                foreign.add(name)
            else:
                inline.add(name)
    listed = set().union(*by_file.values()) if by_file else set()
    return by_file, sorted(inline - listed), sorted(foreign)


def module(file):
    return "DirectedReciprocity." + file.removesuffix(".lean").replace("/", ".")


def tex_escape(name):
    return name.replace("_", r"\_")


def write_index(by_file, inline):
    lines = [
        r"\section{Index of Lean declarations}\label{app:index}",
        "",
        r"This index lists every declaration of this paper's library cited in the text, relative to the namespace",
        r"\texttt{DirectedReciprocity}. The declarations named in status lines are grouped by the module named there; those named only",
        r"in the text are listed at the end. All of them depend only on the axioms \texttt{propext}, \texttt{Classical.choice} and",
        r"\texttt{Quot.sound} (\cref{app:verify}). Declarations of earlier libraries of the series that are named in the text,",
        r"in the namespaces \texttt{Transpose}, \texttt{MotionDepthCodes}, \texttt{DirectedRecovery}, \texttt{HalfRate},",
        r"\texttt{BoundedNesting} and \texttt{SimpleGraph} (\texttt{lean-machine}), are defined and verified in those",
        r"libraries~\cite{FirstPaper2026,FourthPaper2026,DirectedRecovery2026,SeventhPaper2026,EighthPaper2026}; all except the",
        r"standalone \texttt{Transpose} package of~\cite{FirstPaper2026} are also re-checked directly in \leanfile{lean/PaperAxioms.lean}.",
        "",
    ]
    for file in sorted(by_file, key=module):
        decls = sorted(by_file[file])
        lines.append(r"\paragraph{\texttt{" + tex_escape(module(file)) + "}}")
        lines.append(
            r"{\small\raggedright "
            + ", ".join(r"\texttt{" + tex_escape(d) + "}" for d in decls)
            + r".\par}"
        )
        lines.append("")
    if inline:
        lines.append(r"\paragraph{Also named in the text}")
        lines.append(
            r"{\small\raggedright "
            + ", ".join(r"\texttt{" + tex_escape(d) + "}" for d in inline)
            + r".\par}"
        )
        lines.append("")
    SECTIONS.mkdir(parents=True, exist_ok=True)
    (SECTIONS / "leanindex.tex").write_text("\n".join(lines))


def write_axioms(by_file, inline, foreign):
    extra = {"HalfRate", "BoundedNesting"}
    imports = sorted({module(f) for f in by_file} | extra)
    out = [f"import {m}" for m in imports]
    out += [
        "",
        "/-! Generated by tools/lean_index.py from the paper's LaTeX sources: the axioms of every",
        "declaration cited in the paper (including cited declarations of earlier libraries in the",
        "dependency graph). Each should report at most `propext`, `Classical.choice` and",
        "`Quot.sound`. -/",
        "",
    ]
    for file in sorted(by_file, key=module):
        out.append(f"-- {file}")
        for d in sorted(by_file[file]):
            out.append(f"#print axioms DirectedReciprocity.{d}")
    if inline:
        out.append("-- named in the text (DirectedReciprocity)")
        for d in inline:
            out.append(f"#print axioms DirectedReciprocity.{d}")
    dep_foreign = [f for f in foreign if not f.startswith("Transpose.")]
    if dep_foreign:
        out.append("-- named in the text (earlier libraries in dependency graph)")
        for f in dep_foreign:
            out.append(f"#print axioms {f}")
    (ROOT / "lean" / "PaperAxioms.lean").write_text("\n".join(out) + "\n")


def main(argv):
    args = argv[1:]
    unknown = [a for a in args if a != "--index-only"]
    if unknown:
        sys.exit(f"unknown arguments: {' '.join(unknown)}\n{__doc__}")
    by_file, inline, foreign = collect()
    write_index(by_file, inline)
    if "--index-only" in args:
        written = "paper/sections/leanindex.tex"
    else:
        write_axioms(by_file, inline, foreign)
        written = "paper/sections/leanindex.tex and lean/PaperAxioms.lean"
    total = sum(len(v) for v in by_file.values()) + len(inline)
    print(
        f"{total} local declarations in {len(by_file)} modules "
        f"(+{len(foreign)} foreign); wrote {written}"
    )


if __name__ == "__main__":
    main(sys.argv)
