#!/usr/bin/env python3
"""Generate/check the memo's Lean index and axiom audit from its LaTeX sources.

Run from the memo directory: python3 tools/lean_index.py [--check]
Only this memo's CascadeObstruction declarations are collected. Imported
results labelled as cited retain their original paper's verification record.
SPDX-License-Identifier: Apache-2.0
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FORMAL = re.compile(r"\\(?:formal|partformal)\{([^{}]+)\}\{([^{}]+)\}")
INLINE = re.compile(r"\\lean\{(CascadeObstruction\.[^{}]+)\}")


def outputs():
    groups = {}
    inline = set()
    for path in sorted((ROOT / "paper/sections").glob("*.tex")):
        if path.name == "leanindex.tex":
            continue
        source = path.read_text()
        for file, names in FORMAL.findall(source):
            if not (ROOT / "lean" / file).is_file():
                raise ValueError("Missing declared Lean source: " + file)
            group = groups.setdefault(file, set())
            for name in names.split(","):
                name = name.strip()
                if not name.startswith("CascadeObstruction."):
                    raise ValueError("Unexpected declaration namespace: " + name)
                group.add(name)
        inline.update(INLINE.findall(source))
    listed = set().union(*groups.values()) if groups else set()
    extra = sorted(inline - listed)
    tex = [r"\section{Index of new Lean declarations}",
           r"\label{sec:leanindex}", "",
           "Generated with the axiom audit from this memo's formal-status lines.", ""]
    for file, names in sorted(groups.items()):
        tex += [r"\paragraph{\texttt{" + file.replace("_", r"\_") + "}}",
                r"{\small\raggedright " + ", ".join(
                    r"\lean{" + name + "}" for name in sorted(names)) + r".\par}", ""]
    if extra:
        tex += [r"\paragraph{Also named in the text}",
                r"{\small\raggedright " + ", ".join(
                    r"\lean{" + name + "}" for name in extra) + r".\par}", ""]
    audit = ["import CascadeObstruction", "",
             "/-! Generated by tools/lean_index.py; standard-axiom audit. -/", ""]
    audit += ["#print axioms " + name for name in sorted(listed | inline)]
    return {
        ROOT / "paper/sections/leanindex.tex": "\n".join(tex).rstrip() + "\n",
        ROOT / "lean/PaperAxioms.lean": "\n".join(audit) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit("Out of date: " + str(path.relative_to(ROOT)))
        else:
            path.write_text(expected)
    print("Lean index and axiom audit " + ("match" if args.check else "generated"))


if __name__ == "__main__":
    main()
