#!/usr/bin/env python3
"""Shared generator for manuscript Lean indices and axiom audits.

Paper-local tools/lean_index.py wrappers call generate(paper_root, namespace).
Every public local module is imported; cited declarations are audited separately.
"""
import re
from pathlib import Path
PATTERN = re.compile(r"\\(?:formal|partformal)\{([^{}]+)\}\{([^{}]+)\}")
def generate(paper_root: Path, namespace: str):
    ROOT = paper_root.resolve()
    NAMESPACE = namespace
    public_modules = sorted(
        NAMESPACE + "." + path.relative_to(ROOT / "lean" / NAMESPACE)
        .with_suffix("").as_posix().replace("/", ".")
        for path in (ROOT / "lean" / NAMESPACE).rglob("*.lean")
    )
    files = {}
    foreign = set()
    inline = set()
    for source in sorted((ROOT / "paper/sections").glob("*.tex")):
        if source.name == "leanindex.tex": continue
        text = source.read_text()
        inline.update(re.findall(r"\\lean\{([^{}]+)\}", text))
        foreign.update(re.findall(r"\\lean\{((?:NativeRelations|SwapRigidity|LeanMachine|TapeStorageRates)\.[^{}]+)\}", text))
        for file, names in PATTERN.findall(text):
            path = ROOT / "lean" / NAMESPACE / file
            if not path.is_file(): raise SystemExit(f"Missing cited Lean file: {file}")
            files.setdefault(file, set()).update(n.strip() for n in names.split(",") if n.strip())
    for name in inline | foreign | set().union(*files.values()):
        if not name or re.search(r"[\s,]", name):
            raise ValueError(f"Expected one Lean declaration, got {name!r}; "
                             r"use separate \lean{...} commands for inline names")
    (ROOT / "lean" / (NAMESPACE + ".lean")).write_text(
        "-- Generated by tools/lean_index.py; imports every public local module.\n"
        + "\n".join("import " + module for module in public_modules) + "\n"
    )
    modules = {f: NAMESPACE + "." + f.removesuffix(".lean").replace("/", ".") for f in files}
    listed = set().union(*files.values()) if files else set()
    extra = inline - listed - foreign
    audit = ["import " + m for m in sorted(set(modules.values()) | ({NAMESPACE} if extra else set()))]
    if any(n.startswith("NativeRelations.") for n in foreign):
        audit.append("import NativeRelations.OneFreeHeadSmallExcursion")
    audit += ["", "-- Generated from formal-status lines in paper/sections/*.tex.", ""]
    index = [r"\section{Index of Lean declarations}\label{sec:leanindex}", "",
      "The following declarations are cited by formal-status lines. Names are relative to",
      r"\texttt{" + NAMESPACE + "}. A partial status retains the gap stated at its theorem.", ""]
    for file in sorted(files):
        index += [r"\paragraph{\texttt{" + file.replace("_", r"\_") + "}}", r"{\small\raggedright " +
          ", ".join(r"\lean{" + n + "}" for n in sorted(files[file])) + r".\par}", ""]
        audit += ["-- " + file] + ["#print axioms " + NAMESPACE + "." + n for n in sorted(files[file])]
    if extra:
        audit += ["", "-- Other declarations named in the text."] + ["#print axioms " + (n if n.startswith(NAMESPACE + ".") else NAMESPACE + "." + n) for n in sorted(extra)]
        index += [r"\paragraph{Other declarations named in the text}", r"{\small\raggedright " + ", ".join(r"\lean{" + n + "}" for n in sorted(extra)) + r".\par}", ""]
    if foreign:
        audit += ["", "-- Imported declarations cited in the text."] + ["#print axioms " + n for n in sorted(foreign)]
        index += [r"\paragraph{Imported declarations}", r"{\small\raggedright " + ", ".join(r"\lean{" + n + "}" for n in sorted(foreign)) + r".\par}", ""]
    (ROOT / "lean/PaperAxioms.lean").write_text("\n".join(audit) + "\n")
    (ROOT / "paper/sections/leanindex.tex").write_text("\n".join(index).rstrip() + "\n")
    requests = sum(line.startswith("#print axioms ") for line in audit)
    print(f"{len(public_modules)} public modules; "
          f"{sum(map(len, files.values()))} status declarations in {len(files)} modules; "
          f"{requests} axiom requests")
