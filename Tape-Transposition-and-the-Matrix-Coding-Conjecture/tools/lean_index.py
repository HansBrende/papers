#!/usr/bin/env python3
"""Generate the index and axiom audit from all manuscript Lean citations.

Run from the paper directory: python3 tools/lean_index.py [--check]
The maintained module prefix is MatrixCoding. Declaration names deliberately
retain LeanBacklog for compatibility with earlier proof references.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FORMAL = re.compile(r"\\(?:formal|partformal)\{([^{}]+)\}\{([^{}]+)\}")
INLINE = re.compile(r"\\lean\{([^{}]+)\}")
ALIASES = {"NoCode_TM": "Transpose.Tape.NoCode_TM"}
STANDARD = {"propext", "Classical.choice", "Quot.sound"}


def fullname(name):
    if name in ALIASES:
        return ALIASES[name]
    if name in STANDARD or name.startswith(("LeanBacklog.", "LeanMachine.", "Transpose.")):
        return name
    return "LeanBacklog." + name


def module(file):
    suffix = file.removesuffix('.lean').replace('/', '.')
    if file.startswith('LeanMachine/'):
        path = ROOT.parent / 'lean-machine' / file
        result = suffix
    else:
        path = ROOT / 'lean/MatrixCoding' / file
        result = 'MatrixCoding.' + suffix
    if not path.is_file():
        raise ValueError(f'Missing cited file: {file}')
    return result


def outputs():
    files, inline = {}, set()
    for source in sorted((ROOT / 'paper/sections').glob('*.tex')):
        if source.name in ('leanindex.tex', 'verification.tex'):
            continue
        # Ignore comments, including draft notes in source comments.
        text = '\n'.join(line.split('%', 1)[0] for line in source.read_text().splitlines())
        for file, names in FORMAL.findall(text):
            files.setdefault(file, set()).update(n.strip() for n in names.split(',') if n.strip())
        inline.update(n.strip() for n in INLINE.findall(text))
    listed = set().union(*files.values()) if files else set()
    extra = inline - listed
    for name in listed | extra:
        if not name or re.search(r'[\s,]', name):
            raise ValueError(f'Not one Lean declaration: {name!r}')
    modules = sorted('MatrixCoding.' + f.relative_to(ROOT / 'lean/MatrixCoding').with_suffix('').as_posix().replace('/', '.')
                     for f in (ROOT / 'lean/MatrixCoding').rglob('*.lean'))
    index = [r'\section{Index of Lean declarations}\label{sec:leanindex}', '',
             r'Generated from the formal-status lines and inline declaration references. The paper imports',
             r'\leanfile{MatrixCoding}; its declarations retain the namespace \leanname{LeanBacklog} so that earlier',
             r'references remain valid. Names below are relative to that namespace unless they start with',
             r'\leanname{LeanMachine} or \leanname{Transpose}. A partial status retains the gap stated at its theorem.',
             r'The corresponding axiom audit is \leanfile{PaperAxioms.lean}.', '']
    audit = ['import MatrixCoding', '', '-- Generated by tools/lean_index.py; every manuscript declaration is audited.', '']
    for file in sorted(files, key=module):
        module(file)
        index += [r'\par\medskip\noindent{\bfseries\leanfile{' + module(file) + r'}}\par',
                  r'{\small\raggedright ' + ', '.join(r'\leanname{' + n + '}' for n in sorted(files[file])) + r'.\par}', '']
    if extra:
        index += [r'\paragraph{Other declarations named in the text}',
                  r'{\small\raggedright ' + ', '.join(r'\leanname{' + n + '}' for n in sorted(extra)) + r'.\par}', '']
    names = sorted({fullname(n) for n in listed | extra})
    audit += ['#print axioms ' + n for n in names]
    return {
        ROOT/'lean/MatrixCoding.lean': '-- Generated by tools/lean_index.py; every public local module.\n' + '\n'.join('import '+m for m in modules)+'\n',
        ROOT/'lean/PaperAxioms.lean': '\n'.join(audit)+'\n',
        ROOT/'paper/sections/leanindex.tex': '\n'.join(index).rstrip()+'\n',
    }, len(names), len(modules)


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args=ap.parse_args()
    generated, count, modules=outputs()
    for path, text in generated.items():
        if args.check:
            if not path.is_file() or path.read_text()!=text:
                raise SystemExit(f'Out of date: {path.relative_to(ROOT)}')
        else:
            path.write_text(text)
    print(f'{modules} public modules; {count} distinct axiom requests')


if __name__=='__main__':
    main()
