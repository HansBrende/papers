"""Generate the Lean data of the aperiodic class-uniform example (n = 6 over GF(2), two classes, dimension 25).

Usage:

    python3 tools/gen_aperiodic_example.py            write lean/SwapRigidity/AperiodicExampleData.lean
    python3 tools/gen_aperiodic_example.py --check    write nothing; exit 1 if that file is out of date

The script reads the certificate `data/aperiodic_d6_dim25.json` next to itself and writes
`../lean/SwapRigidity/AperiodicExampleData.lean`.  Both paths are relative to the script, so it can be run from any
directory.  It needs only the Python standard library, and its output is deterministic.

Certificate format:
  n             side length (6);
  classes       a partition of range(n) into lists ([[0, 1, 3], [2, 4, 5]]);
  a             a[J][r] is a list of n*n bits, the functional of class J for output coordinate r; the entry
                (i, j) of a matrix is at position i*n + j;
  kernel_basis  integers; bit i*n + j of each is the entry (i, j) of an n x n matrix over GF(2).
The rule is  X[c][r] = sum_{i,j} a[J(c)][r][i*n + j] * X[i][(j + c) mod n]  for every row c and every r, with
J(c) the index of the class of c.

What is written.  All tables are sparse: a 0/1 table is given by the list of the positions (i, j) of its ones.
  aperiodicCls          the class map (true on classes[0], false on classes[1]);
  aperiodicGenSupports  for every basis matrix, the positions of its ones;
  aperiodicDecSupport   for every class and every r, the positions of the ones of a[J][r];
  aperiodicPivots       for every basis matrix, a *private* position: one where this matrix is 1 and every
                        other basis matrix is 0 (the least such position).  These prove independence.

Before writing, the script re-checks from the definition that every basis matrix satisfies the rule.  It stops
with an error if this fails or if some basis matrix has no private position.  The generated file contains
definitions only; every property is proved in `SwapRigidity/AperiodicExample.lean` and checked by the Lean
kernel, so this script is not trusted.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "data", "aperiodic_d6_dim25.json")
TARGET = os.path.join(HERE, os.pardir, "lean", "SwapRigidity", "AperiodicExampleData.lean")
SOURCE_NAME = "tools/data/aperiodic_d6_dim25.json"
SCRIPT_NAME = "tools/gen_aperiodic_example.py"
TARGET_NAME = "lean/SwapRigidity/AperiodicExampleData.lean"


def load():
    """Read the certificate, check it from the definition and return the tables to be written."""
    with open(SOURCE) as f:
        data = json.load(f)
    n = data["n"]
    classes = data["classes"]
    a = data["a"]
    basis = data["kernel_basis"]
    assert n == 6, "the Lean development is written for n = 6"
    assert len(classes) == 2, "the Lean development is written for two classes"
    assert sorted(c for members in classes for c in members) == list(range(n))
    assert len(a) == 2 and all(len(aJ) == n and all(len(f) == n * n for f in aJ) for aJ in a)
    assert all(bit in (0, 1) for aJ in a for f in aJ for bit in f)
    assert all(0 <= X < 2 ** (n * n) for X in basis)
    cls = {c: J for J, members in enumerate(classes) for c in members}
    mats = [[(X >> p) & 1 for p in range(n * n)] for X in basis]

    # the rule, from the definition
    for k, x in enumerate(mats):
        for c in range(n):
            for r in range(n):
                s = 0
                for i in range(n):
                    for j in range(n):
                        if a[cls[c]][r][i * n + j]:
                            s ^= x[i * n + (j + c) % n]
                assert s == x[c * n + r], f"basis matrix {k} violates the rule at row {c}, coordinate {r}"

    # private positions
    pivots = []
    for k, x in enumerate(mats):
        private = [p for p in range(n * n) if x[p] and not any(y[p] for l, y in enumerate(mats) if l != k)]
        assert private, f"basis matrix {k} has no private position"
        pivots.append(private[0])
    return n, classes, cls, a, mats, pivots


def generate():
    """The text of the Lean data file."""
    n, classes, cls, a, mats, pivots = load()
    d = len(mats)

    def pair(p):
        return f"({p // n}, {p % n})"

    def support(bits):
        return "[" + ", ".join(pair(p) for p in range(n * n) if bits[p]) + "]"

    def braces(members):
        return "{" + ", ".join(map(str, members)) + "}"

    lines = [
        "/-",
        f"Generated by `{SCRIPT_NAME}` from `{SOURCE_NAME}`.",
        "Do not edit this file: change the generator and run it again.",
        "-/",
        "import Mathlib.Data.Fin.VecNotation",
        "import Mathlib.Data.ZMod.Defs",
        "",
        "/-!",
        "# Data of the aperiodic class-uniform example",
        "",
        f"The certificate `{SOURCE_NAME}` describes a class-uniform code of dimension {d}",
        f"in the `{n} × {n}` matrices over `ZMod 2`, for the two row classes `{braces(classes[0])}` and "
        f"`{braces(classes[1])}` of",
        f"`ZMod {n}`.  This file holds its data and nothing else.  Every table is sparse: a `0/1` table is",
        "given by the list of the positions `(i, j)` (row, column) of its ones.",
        "",
        "* `aperiodicCls`: the class map;",
        f"* `aperiodicGenSupports`: the supports of the {d} generators of the code;",
        "* `aperiodicDecSupport`: the supports of the coefficients of the two decoders;",
        "* `aperiodicPivots`: for every generator, a position where it is `1` and the others are `0`.",
        "",
        "The matrices, the decoders and all proofs are in `SwapRigidity.AperiodicExample`.",
        "-/",
        "",
        "namespace SwapRigidity",
        "",
        f"/-- The class map of the example: `true` on the class `{braces(classes[0])}` of `ZMod {n}` and "
        f"`false` on the",
        f"class `{braces(classes[1])}` (the key `classes` of the certificate). -/",
        f"def aperiodicCls : ZMod {n} → Bool :=",
        "  ![" + ", ".join("true" if cls[c] == 0 else "false" for c in range(n)) + "]",
        "",
        f"/-- The supports of the {d} generators of the example code, in the order of the key "
        f"`kernel_basis`",
        f"of the certificate: entry `k` lists the positions `(i, j)` at which generator `k` is `1`, that "
        f"is,",
        f"the bits `i * {n} + j` of `kernel_basis[k]` that are set. -/",
        f"def aperiodicGenSupports : List (List (ZMod {n} × ZMod {n})) :=",
        "  [" + ",\n   ".join(support(x) for x in mats) + "]",
        "",
        "/-- The supports of the decoder coefficients of the example (the key `a` of the certificate):",
        "`aperiodicDecSupport k r` lists the entries `(i, j)` of the rotated matrix whose sum is output",
        f"coordinate `r` of the decoder of class `k`, that is, the positions `i * {n} + j` at which "
        f"`a[J][r]` is",
        f"`1`.  The class `true` is `J = 0` (the rows `{braces(classes[0])}`) and the class `false` is "
        f"`J = 1` (the rows",
        f"`{braces(classes[1])}`). -/",
        f"def aperiodicDecSupport : Bool → ZMod {n} → List (ZMod {n} × ZMod {n})",
    ]
    for J, name in ((0, "true"), (1, "false")):
        lines.append(f"  | {name} =>")
        lines.append("    ![" + ",\n      ".join(support(a[J][r]) for r in range(n)) + "]")
    piv = [pair(p) for p in pivots]
    lines += [
        "",
        "/-- A private position of each generator: generator `k` is `1` at entry `k` of this list and "
        "every",
        "other generator is `0` there. -/",
        f"def aperiodicPivots : List (ZMod {n} × ZMod {n}) :=",
        "  [" + ",\n   ".join(", ".join(piv[s:s + 8]) for s in range(0, d, 8)) + "]",
        "",
        "end SwapRigidity",
    ]
    text = "\n".join(lines) + "\n"
    too_long = [line for line in text.splitlines() if len(line) > 100]
    assert not too_long, too_long
    return text


def main(argv):
    if argv[1:] not in ([], ["--check"]):
        print(__doc__)
        return 2
    text = generate()
    if argv[1:] == ["--check"]:
        with open(TARGET) as f:
            same = f.read() == text
        print(f"{TARGET_NAME}: " + ("up to date" if same else "DIFFERENT from the generated text"))
        return 0 if same else 1
    with open(TARGET, "w") as f:
        f.write(text)
    print(f"wrote {TARGET_NAME} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
